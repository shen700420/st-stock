// 股票代號 → 族群名稱的反向查找表（供個股查詢所屬族群）
export function buildReverseMap() {
  const map = {};
  for (const [sectorName, sectorData] of Object.entries(SECTORS)) {
    for (const stock of sectorData.stocks) {
      if (!map[stock]) map[stock] = [];
      map[stock].push(sectorName);
    }
  }
  return map;
}

// 取得個股所屬族群
export function getStockSectors(symbol, reverseMap) {
  return reverseMap[symbol] || ["未分類"];
}

// 取得族群所有代號（統一格式）
export function getSectorStocks(sectorName) {
  return SECTORS[sectorName]?.stocks || [];
}

// 列出所有族群名稱
export function listSectors() {
  return Object.entries(SECTORS).map(([name, data]) => ({
    name,
    desc: data.desc,
    count: data.stocks.length,
  }));
}
